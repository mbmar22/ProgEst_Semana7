# Cadena de caracteres
nombre = "María Belén Martínez Ortega"

texto = "                      "

print("Nombre:", end = " ")
print(nombre)
print("Texto:", end = " ")
print(texto)

# Tamaño de la cadena
print("Nombre:", end = " ")
print(len(nombre))
print("Texto:", end = " ")
print(len(texto))

# Limpiar espacios
print("Nombre:", end = " ")
print(nombre)
print("Texto:", end = " ")
print(texto.strip())